export const HOME_COLLECTION_FEE_USD = 35;

export function getLabTestBySlug(slug: string): LabTest | undefined {
  return labTests.find((t) => t.slug === slug);
}

export function getLabTestById(id: string): LabTest | undefined {
  return labTests.find((t) => t.id === id);
}

export function getLabCategoryMeta(id: string): LabCategoryMeta | undefined {
  return labCategories.find((c) => c.id === id);
}

export function getPopularLabTests(limit = 4): LabTest[] {
  return labTests.filter((t) => t.popular).slice(0, limit);
}

export function getRelatedLabTests(test: LabTest, limit = 3): LabTest[] {
  return labTests.filter((t) => t.id !== test.id && t.category === test.category).slice(0, limit);
}
