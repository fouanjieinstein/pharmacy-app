export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByCategory(category: string): Product[] {
  return products.filter((p) => p.category === category);
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  return products
    .filter((p) => p.id !== product.id && p.category === product.category)
    .sort((a, b) => Number(b.sponsored) - Number(a.sponsored) || b.popularityScore - a.popularityScore)
    .slice(0, limit);
}

export function getFeaturedProducts(limit = 8): Product[] {
  return products.filter((p) => p.featured).slice(0, limit);
}

/** Sibling pack-size/strength entries sharing the same variantGroup, sorted
 * by price — powers the "Select Available Variant" switcher on the product
 * detail page. Returns an empty array for products with no variant group. */
export function getVariantSiblings(product: Product): Product[] {
  if (!product.variantGroup) return [];
  return products
    .filter((p) => p.variantGroup === product.variantGroup)
    .sort((a, b) => a.priceUsd - b.priceUsd);
}
